CREATE TABLE action_item_evidence (
	evidence_id VARCHAR(24) NOT NULL, 
	action_id VARCHAR(24) NOT NULL, 
	source_type VARCHAR(24) NOT NULL, 
	response_id VARCHAR(40), 
	review_id VARCHAR(24), 
	message_id VARCHAR(40), 
	contribution_weight FLOAT NOT NULL, 
	linked_at DATETIME NOT NULL, 
	PRIMARY KEY (evidence_id), 
	CONSTRAINT ck_evid_exact_one_parent CHECK ((CASE WHEN response_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN review_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN message_id IS NOT NULL THEN 1 ELSE 0 END) = 1), 
	CONSTRAINT ck_evid_source_type CHECK (source_type IN ('SURVEY_RESPONSE','REVIEW','SUPPORT_MESSAGE')), 
	CONSTRAINT ck_evid_wt CHECK (contribution_weight > 0.0 AND contribution_weight <= 1.0), 
	FOREIGN KEY(action_id) REFERENCES action_items (action_id), 
	FOREIGN KEY(response_id) REFERENCES survey_responses (response_id), 
	FOREIGN KEY(review_id) REFERENCES reviews (review_id), 
	FOREIGN KEY(message_id) REFERENCES support_messages (message_id)
);

CREATE TABLE lifecycle_events (
	event_id VARCHAR(24) NOT NULL, 
	entity_type VARCHAR(24) NOT NULL, 
	entity_id VARCHAR(48) NOT NULL, 
	from_state VARCHAR(32), 
	to_state VARCHAR(32) NOT NULL, 
	actor VARCHAR(64) NOT NULL, 
	reason TEXT NOT NULL, 
	event_timestamp DATETIME NOT NULL, 
	sequence_no INTEGER NOT NULL, 
	PRIMARY KEY (event_id), 
	CONSTRAINT ck_evt_entity_type CHECK (entity_type IN ('SURVEY', 'SURVEY_RESPONSE', 'REVIEW', 'SUPPORT_TICKET', 'SUPPORT_MESSAGE', 'ACTION_ITEM')), 
