CREATE TABLE sentiment_shifts (
	shift_id VARCHAR(24) NOT NULL, 
	product_id VARCHAR(16), 
	theme_id VARCHAR(20), 
	channel_group VARCHAR(20), 
	baseline_start DATETIME NOT NULL, 
	baseline_end DATETIME NOT NULL, 
	current_start DATETIME NOT NULL, 
	current_end DATETIME NOT NULL, 
	baseline_count INTEGER NOT NULL, 
	current_count INTEGER NOT NULL, 
	baseline_avg_score FLOAT NOT NULL, 
	current_avg_score FLOAT NOT NULL, 
	delta_score FLOAT NOT NULL, 
	z_score FLOAT NOT NULL, 
	direction VARCHAR(16) NOT NULL, 
	is_significant BOOLEAN NOT NULL, 
	detected_at DATETIME NOT NULL, 
	PRIMARY KEY (shift_id), 
	CONSTRAINT ck_shift_channel_group CHECK (channel_group IS NULL OR channel_group IN ('SURVEY','REVIEW','SUPPORT')), 
	CONSTRAINT ck_shift_dir CHECK (direction IN ('IMPROVING','DECLINING','STABLE')), 
	CONSTRAINT ck_shift_base_dates CHECK (baseline_end >= baseline_start), 
	CONSTRAINT ck_shift_curr_dates CHECK (current_end >= current_start), 
	CONSTRAINT ck_shift_order CHECK (current_start >= baseline_start), 
	CONSTRAINT ck_shift_counts CHECK (baseline_count >= 0 AND current_count >= 0), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(theme_id) REFERENCES themes (theme_id)
);

