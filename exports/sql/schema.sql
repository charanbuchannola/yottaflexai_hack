-- YottaFlex Voice of Customer Intelligence Platform DDL
PRAGMA foreign_keys = ON;

CREATE TABLE channels (
	channel_id VARCHAR(16) NOT NULL, 
	channel_code VARCHAR(40) NOT NULL, 
	channel_group VARCHAR(20) NOT NULL, 
	is_public BOOLEAN NOT NULL, 
	requires_moderation BOOLEAN NOT NULL, 
	default_sla_hours INTEGER NOT NULL, 
	is_active BOOLEAN NOT NULL, 
	effective_from DATETIME NOT NULL, 
	effective_to DATETIME, 
	PRIMARY KEY (channel_id), 
	CONSTRAINT ck_channel_group CHECK (channel_group IN ('SURVEY','REVIEW','SUPPORT')), 
	CONSTRAINT ck_channel_sla CHECK (default_sla_hours > 0), 
	CONSTRAINT ck_channel_dates CHECK (effective_to IS NULL OR effective_to >= effective_from), 
	UNIQUE (channel_code)
);

CREATE TABLE products (
	product_id VARCHAR(16) NOT NULL, 
	sku VARCHAR(32) NOT NULL, 
	product_name VARCHAR(120) NOT NULL, 
	category VARCHAR(40) NOT NULL, 
	release_version VARCHAR(24) NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	support_sla_hours INTEGER NOT NULL, 
	effective_from DATETIME NOT NULL, 
	effective_to DATETIME, 
	PRIMARY KEY (product_id), 
	CONSTRAINT ck_product_category CHECK (category IN ('CORE_PLATFORM','ANALYTICS_SUITE','MOBILE_APP','BILLING_ADDON','API_GATEWAY')), 
	CONSTRAINT ck_product_state CHECK (lifecycle_state IN ('BETA','GA','SUNSETTING','DEPRECATED')), 
	CONSTRAINT ck_product_sla CHECK (support_sla_hours > 0), 
	CONSTRAINT ck_product_dates CHECK (effective_to IS NULL OR effective_to >= effective_from), 
	UNIQUE (sku)
);

CREATE TABLE themes (
	theme_id VARCHAR(20) NOT NULL, 
	theme_code VARCHAR(64) NOT NULL, 
	theme_name VARCHAR(120) NOT NULL, 
	parent_theme_id VARCHAR(20), 
	category VARCHAR(40) NOT NULL, 
	severity_weight FLOAT NOT NULL, 
	keywords_json TEXT NOT NULL, 
	is_active BOOLEAN NOT NULL, 
	effective_from DATETIME NOT NULL, 
	effective_to DATETIME, 
	PRIMARY KEY (theme_id), 
	CONSTRAINT ck_theme_category CHECK (category IN ('PERFORMANCE_RELIABILITY','BILLING_PRICING','SUPPORT_EXPERIENCE','UX_ONBOARDING','PRODUCT_QUALITY','INTEGRATIONS','SECURITY_PRIVACY')), 
	CONSTRAINT ck_theme_weight CHECK (severity_weight > 0.0 AND severity_weight <= 2.5), 
	CONSTRAINT ck_theme_dates CHECK (effective_to IS NULL OR effective_to >= effective_from), 
	UNIQUE (theme_code), 
	FOREIGN KEY(parent_theme_id) REFERENCES themes (theme_id)
);

CREATE TABLE customers (
	customer_id VARCHAR(20) NOT NULL, 
	pseudonym_handle VARCHAR(32) NOT NULL, 
	account_tier VARCHAR(20) NOT NULL, 
	segment VARCHAR(20) NOT NULL, 
	region VARCHAR(16) NOT NULL, 
	preferred_language VARCHAR(8) NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	effective_from DATETIME NOT NULL, 
	effective_to DATETIME, 
	created_at DATETIME NOT NULL, 
	PRIMARY KEY (customer_id), 
	CONSTRAINT ck_customer_tier CHECK (account_tier IN ('FREE','PRO','ENTERPRISE')), 
	CONSTRAINT ck_customer_segment CHECK (segment IN ('CONSUMER','SMB','MID_MARKET','ENTERPRISE')), 
	CONSTRAINT ck_customer_region CHECK (region IN ('NA','EMEA','APAC','LATAM')), 
	CONSTRAINT ck_customer_lang CHECK (preferred_language IN ('en','es','fr','de')), 
	CONSTRAINT ck_customer_state CHECK (lifecycle_state IN ('PROSPECT','ACTIVE','AT_RISK','CHURNED')), 
	CONSTRAINT ck_customer_dates CHECK (effective_to IS NULL OR effective_to >= effective_from), 
	UNIQUE (pseudonym_handle)
);

CREATE TABLE surveys (
	survey_id VARCHAR(24) NOT NULL, 
	product_id VARCHAR(16), 
	channel_id VARCHAR(16) NOT NULL, 
	survey_type VARCHAR(24) NOT NULL, 
	title VARCHAR(160) NOT NULL, 
	question_prompt TEXT NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	target_response_count INTEGER NOT NULL, 
	actual_response_count INTEGER NOT NULL, 
	effective_from DATETIME NOT NULL, 
	effective_to DATETIME NOT NULL, 
	PRIMARY KEY (survey_id), 
	CONSTRAINT ck_survey_type CHECK (survey_type IN ('NPS','CSAT','CES','POST_ONBOARDING')), 
	CONSTRAINT ck_survey_state CHECK (lifecycle_state IN ('DRAFT','ACTIVE','CLOSED','ARCHIVED')), 
	CONSTRAINT ck_survey_target CHECK (target_response_count >= 0), 
	CONSTRAINT ck_survey_actual CHECK (actual_response_count >= 0), 
	CONSTRAINT ck_survey_dates CHECK (effective_to >= effective_from), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE survey_responses (
	response_id VARCHAR(40) NOT NULL, 
	survey_id VARCHAR(24) NOT NULL, 
	customer_id VARCHAR(20) NOT NULL, 
	product_id VARCHAR(16), 
	channel_id VARCHAR(16) NOT NULL, 
	rating_score INTEGER NOT NULL, 
	normalized_score FLOAT NOT NULL, 
	response_text TEXT NOT NULL, 
	language VARCHAR(8) NOT NULL, 
	submitted_at DATETIME NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	content_hash VARCHAR(64) NOT NULL, 
	PRIMARY KEY (response_id), 
	CONSTRAINT ck_resp_lang CHECK (language IN ('en','es','fr','de')), 
	CONSTRAINT ck_resp_state CHECK (lifecycle_state IN ('SUBMITTED','ANALYZED','VERIFIED','FLAGGED','QUARANTINED')), 
	CONSTRAINT ck_resp_rating CHECK (rating_score >= 0 AND rating_score <= 10), 
	CONSTRAINT ck_resp_norm CHECK (normalized_score >= 0.0 AND normalized_score <= 1.0), 
	FOREIGN KEY(survey_id) REFERENCES surveys (survey_id), 
	FOREIGN KEY(customer_id) REFERENCES customers (customer_id), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE reviews (
	review_id VARCHAR(24) NOT NULL, 
	customer_id VARCHAR(20), 
	product_id VARCHAR(16) NOT NULL, 
	channel_id VARCHAR(16) NOT NULL, 
	star_rating INTEGER NOT NULL, 
	title VARCHAR(200) NOT NULL, 
	review_text TEXT NOT NULL, 
	language VARCHAR(8) NOT NULL, 
	verified_purchase BOOLEAN NOT NULL, 
	helpful_votes INTEGER NOT NULL, 
	published_at DATETIME NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	content_hash VARCHAR(64) NOT NULL, 
	PRIMARY KEY (review_id), 
	CONSTRAINT ck_rev_lang CHECK (language IN ('en','es','fr','de')), 
	CONSTRAINT ck_rev_state CHECK (lifecycle_state IN ('SUBMITTED','ANALYZED','VERIFIED','FLAGGED','QUARANTINED')), 
	CONSTRAINT ck_rev_stars CHECK (star_rating >= 1 AND star_rating <= 5), 
	CONSTRAINT ck_rev_votes CHECK (helpful_votes >= 0), 
	FOREIGN KEY(customer_id) REFERENCES customers (customer_id), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE support_tickets (
	ticket_id VARCHAR(24) NOT NULL, 
	customer_id VARCHAR(20) NOT NULL, 
	product_id VARCHAR(16) NOT NULL, 
	channel_id VARCHAR(16) NOT NULL, 
	subject VARCHAR(200) NOT NULL, 
	priority VARCHAR(16) NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	message_count INTEGER NOT NULL, 
	opened_at DATETIME NOT NULL, 
	resolved_at DATETIME, 
	PRIMARY KEY (ticket_id), 
	CONSTRAINT ck_tkt_priority CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')), 
	CONSTRAINT ck_tkt_state CHECK (lifecycle_state IN ('OPEN','TRIAGED','IN_PROGRESS','ESCALATED','RESOLVED','CLOSED')), 
	CONSTRAINT ck_tkt_dates CHECK (resolved_at IS NULL OR resolved_at >= opened_at), 
	CONSTRAINT ck_tkt_msg_count CHECK (message_count >= 0), 
	FOREIGN KEY(customer_id) REFERENCES customers (customer_id), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE support_messages (
	message_id VARCHAR(40) NOT NULL, 
	ticket_id VARCHAR(24) NOT NULL, 
	customer_id VARCHAR(20) NOT NULL, 
	product_id VARCHAR(16) NOT NULL, 
	channel_id VARCHAR(16) NOT NULL, 
	sender_role VARCHAR(20) NOT NULL, 
	sequence_no INTEGER NOT NULL, 
	message_text TEXT NOT NULL, 
	language VARCHAR(8) NOT NULL, 
	sent_at DATETIME NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	content_hash VARCHAR(64) NOT NULL, 
	PRIMARY KEY (message_id), 
	CONSTRAINT ck_msg_sender CHECK (sender_role IN ('CUSTOMER','SUPPORT_AGENT','SYSTEM_BOT')), 
	CONSTRAINT ck_msg_lang CHECK (language IN ('en','es','fr','de')), 
	CONSTRAINT ck_msg_state CHECK (lifecycle_state IN ('SUBMITTED','ANALYZED','VERIFIED','FLAGGED','QUARANTINED')), 
	CONSTRAINT ck_msg_seq CHECK (sequence_no >= 1), 
	FOREIGN KEY(ticket_id) REFERENCES support_tickets (ticket_id), 
	FOREIGN KEY(customer_id) REFERENCES customers (customer_id), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE model_inputs (
	input_id VARCHAR(24) NOT NULL, 
	source_type VARCHAR(24) NOT NULL, 
	response_id VARCHAR(40), 
	review_id VARCHAR(24), 
	message_id VARCHAR(40), 
	product_id VARCHAR(16), 
	channel_id VARCHAR(16) NOT NULL, 
	language VARCHAR(8) NOT NULL, 
	event_timestamp DATETIME NOT NULL, 
	text_payload TEXT NOT NULL, 
	rating_signal FLOAT, 
	split_partition VARCHAR(16) NOT NULL, 
	extra_features_json TEXT NOT NULL, 
	PRIMARY KEY (input_id), 
	CONSTRAINT ck_inp_exact_one_parent CHECK ((CASE WHEN response_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN review_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN message_id IS NOT NULL THEN 1 ELSE 0 END) = 1), 
	CONSTRAINT ck_inp_source_type CHECK (source_type IN ('SURVEY_RESPONSE','REVIEW','SUPPORT_MESSAGE')), 
	CONSTRAINT ck_inp_lang CHECK (language IN ('en','es','fr','de')), 
	CONSTRAINT ck_inp_split CHECK (split_partition IN ('TRAIN', 'INFERENCE', 'TEST')), 
	CONSTRAINT uq_inp_resp UNIQUE (response_id), 
	CONSTRAINT uq_inp_rev UNIQUE (review_id), 
	CONSTRAINT uq_inp_msg UNIQUE (message_id), 
	FOREIGN KEY(response_id) REFERENCES survey_responses (response_id), 
	FOREIGN KEY(review_id) REFERENCES reviews (review_id), 
	FOREIGN KEY(message_id) REFERENCES support_messages (message_id), 
	FOREIGN KEY(product_id) REFERENCES products (product_id), 
	FOREIGN KEY(channel_id) REFERENCES channels (channel_id)
);

CREATE TABLE sentiment_labels (
	label_id VARCHAR(24) NOT NULL, 
	source_type VARCHAR(24) NOT NULL, 
	response_id VARCHAR(40), 
	review_id VARCHAR(24), 
	message_id VARCHAR(40), 
	polarity VARCHAR(16) NOT NULL, 
	sentiment_score FLOAT NOT NULL, 
	confidence FLOAT NOT NULL, 
	labeling_method VARCHAR(24) NOT NULL, 
	rationale TEXT, 
	labeled_at DATETIME NOT NULL, 
	lifecycle_state VARCHAR(20) NOT NULL, 
	PRIMARY KEY (label_id), 
	CONSTRAINT ck_sent_exact_one_parent CHECK ((CASE WHEN response_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN review_id IS NOT NULL THEN 1 ELSE 0 END + CASE WHEN message_id IS NOT NULL THEN 1 ELSE 0 END) = 1), 
	CONSTRAINT ck_sent_source_type CHECK (source_type IN ('SURVEY_RESPONSE','REVIEW','SUPPORT_MESSAGE')), 
	CONSTRAINT ck_sent_polarity CHECK (polarity IN ('POSITIVE','NEGATIVE','NEUTRAL','MIXED')), 
	CONSTRAINT ck_sent_score CHECK (sentiment_score >= -1.0 AND sentiment_score <= 1.0), 
	CONSTRAINT ck_sent_conf CHECK (confidence >= 0.0 AND confidence <= 1.0), 
	CONSTRAINT ck_sent_method CHECK (labeling_method IN ('AUTOMATED_NLP','INGESTED_PROVIDER')), 
	CONSTRAINT ck_sent_state CHECK (lifecycle_state IN ('SUBMITTED','ANALYZED','VERIFIED','FLAGGED','QUARANTINED')), 
	UNIQUE (response_id), 
	FOREIGN KEY(response_id) REFERENCES survey_responses (response_id), 
	UNIQUE (review_id), 
	FOREIGN KEY(review_id) REFERENCES reviews (review_id), 
	UNIQUE (message_id), 
	FOREIGN KEY(message_id) REFERENCES support_messages (message_id)
);

